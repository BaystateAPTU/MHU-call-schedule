"""Core logic for the call volunteer / assignment app (no Streamlit imports)."""
from __future__ import annotations

import hashlib
import io
import os
import sqlite3
from contextlib import contextmanager
from datetime import date, timedelta

import pandas as pd

DB_PATH = os.environ.get("CALL_DB", "call_schedule.db")
LEVELS = ("Preferred", "Willing")
TYPES = ("weekday", "weekend")  # holidays are flagged, not a separate shift type

# Storage: if DATABASE_URL is set (Neon / Supabase Postgres), use it. Otherwise fall
# back to a local SQLite file, which is fine on your own computer but is WIPED on
# Streamlit Community Cloud whenever the app restarts.

_TABLES = """
CREATE TABLE IF NOT EXISTS people (
    id {pk},
    name TEXT UNIQUE NOT NULL,
    pin_hash TEXT NOT NULL,
    active INTEGER NOT NULL DEFAULT 1,
    carry_weekday INTEGER NOT NULL DEFAULT 0,
    carry_weekend INTEGER NOT NULL DEFAULT 0,
    carry_holiday INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS blocks (
    id {pk},
    name TEXT NOT NULL,
    start_date TEXT NOT NULL,
    end_date TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'open'
);
CREATE TABLE IF NOT EXISTS holidays (
    date TEXT PRIMARY KEY,
    name TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS availability (
    block_id INTEGER NOT NULL REFERENCES blocks(id) ON DELETE CASCADE,
    person_id INTEGER NOT NULL REFERENCES people(id) ON DELETE CASCADE,
    date TEXT NOT NULL,
    level TEXT NOT NULL,
    PRIMARY KEY (block_id, person_id, date)
);
CREATE TABLE IF NOT EXISTS assignments (
    block_id INTEGER NOT NULL REFERENCES blocks(id) ON DELETE CASCADE,
    date TEXT NOT NULL,
    person_id INTEGER NOT NULL REFERENCES people(id) ON DELETE CASCADE,
    PRIMARY KEY (block_id, date)
)
"""
SCHEMA_SQLITE = _TABLES.format(pk="INTEGER PRIMARY KEY AUTOINCREMENT")
SCHEMA_PG = _TABLES.format(pk="INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")


def database_url() -> str:
    return os.environ.get("DATABASE_URL", "").strip()


def using_postgres() -> bool:
    return bool(database_url())


def _plain(v):
    """numpy / pandas scalars -> plain Python so the Postgres driver accepts them."""
    return v.item() if hasattr(v, "item") and not isinstance(v, (str, bytes)) else v


def _params(params) -> tuple:
    return tuple(_plain(v) for v in params)


class _PGConn:
    """Thin wrapper so Postgres accepts the same '?'-style SQL as sqlite3."""

    def __init__(self, raw):
        self.raw = raw

    @staticmethod
    def _sql(sql: str) -> str:
        return sql.replace("%", "%%").replace("?", "%s")

    def execute(self, sql: str, params: tuple = ()):
        cur = self.raw.cursor()
        cur.execute(self._sql(sql), _params(params))
        return cur

    def executemany(self, sql: str, seq) -> None:
        seq = [_params(p) for p in seq]
        if seq:
            self.raw.cursor().executemany(self._sql(sql), seq)


_pool = None


def _pg_pool():
    global _pool
    if _pool is None:
        from psycopg.rows import dict_row
        from psycopg_pool import ConnectionPool

        _pool = ConnectionPool(
            database_url(),
            min_size=1,
            max_size=4,
            # prepare_threshold=None keeps it compatible with Supabase/Neon poolers.
            kwargs={"row_factory": dict_row, "prepare_threshold": None},
            check=ConnectionPool.check_connection,  # re-dial if Neon dropped an idle connection
            open=True,
        )
        import atexit

        atexit.register(_pool.close)
    return _pool


@contextmanager
def conn():
    if using_postgres():
        with _pg_pool().connection() as raw:  # commits on success, rolls back on error
            yield _PGConn(raw)
        return
    c = sqlite3.connect(DB_PATH)
    c.row_factory = sqlite3.Row
    c.execute("PRAGMA foreign_keys = ON")
    try:
        yield c
        c.commit()
    finally:
        c.close()


def init_db() -> None:
    with conn() as c:
        if using_postgres():
            for stmt in SCHEMA_PG.split(";"):
                if stmt.strip():
                    c.execute(stmt)
        else:
            c.executescript(SCHEMA_SQLITE)


def query(sql: str, params: tuple = ()) -> list[dict]:
    with conn() as c:
        return [dict(r) for r in c.execute(sql, _params(params)).fetchall()]


def execute(sql: str, params: tuple = ()) -> None:
    with conn() as c:
        c.execute(sql, _params(params))


# ------------------------------------------------------------------- people
def hash_pin(pin: str) -> str:
    return hashlib.pbkdf2_hmac("sha256", pin.encode(), b"call-volunteer-v1", 50_000).hex()


def clean_name(name: str) -> str:
    return " ".join(name.split())


def name_taken(name: str) -> bool:
    rows = query("SELECT 1 FROM people WHERE LOWER(name)=LOWER(?)", (clean_name(name),))
    return bool(rows)


def add_person(name: str, pin: str) -> int:
    with conn() as c:
        cur = c.execute(
            "INSERT INTO people (name, pin_hash) VALUES (?, ?) RETURNING id",
            (clean_name(name), hash_pin(pin)),
        )
        return cur.fetchone()["id"]


def set_pin(person_id: int, pin: str) -> None:
    execute("UPDATE people SET pin_hash=? WHERE id=?", (hash_pin(pin), person_id))


def check_pin(person_id: int, pin: str) -> bool:
    rows = query("SELECT pin_hash FROM people WHERE id=?", (person_id,))
    return bool(rows) and rows[0]["pin_hash"] == hash_pin(pin)


def get_people(active_only: bool = True) -> list[dict]:
    sql = "SELECT * FROM people" + (" WHERE active=1" if active_only else "") + " ORDER BY name"
    return query(sql)


# ------------------------------------------------------------------- blocks
def create_block(name: str, start: date, end: date) -> int:
    with conn() as c:
        cur = c.execute(
            "INSERT INTO blocks (name, start_date, end_date) VALUES (?,?,?) RETURNING id",
            (name, start.isoformat(), end.isoformat()),
        )
        return cur.fetchone()["id"]


def get_blocks(status: str | None = None) -> list[dict]:
    if status:
        return query("SELECT * FROM blocks WHERE status=? ORDER BY start_date DESC", (status,))
    return query("SELECT * FROM blocks ORDER BY start_date DESC")


def block_dates(block: dict) -> list[date]:
    d, end = date.fromisoformat(block["start_date"]), date.fromisoformat(block["end_date"])
    out = []
    while d <= end:
        out.append(d)
        d += timedelta(days=1)
    return out


def six_month_end(start: date) -> date:
    return (pd.Timestamp(start) + pd.DateOffset(months=6) - pd.Timedelta(days=1)).date()


# ----------------------------------------------------------------- holidays
def get_holidays() -> dict[str, str]:
    return {r["date"]: r["name"] for r in query("SELECT date, name FROM holidays")}


def replace_holidays(rows: list[tuple[str, str]]) -> None:
    with conn() as c:
        c.execute("DELETE FROM holidays")
        c.executemany("INSERT INTO holidays (date, name) VALUES (?,?) "
            "ON CONFLICT (date) DO UPDATE SET name = excluded.name", rows)


def add_holiday_range(name: str, start: date, end: date) -> int:
    """Flag every date from start to end (inclusive) as a holiday. Returns days added/updated."""
    rows = []
    d = start
    while d <= end:
        rows.append((d.isoformat(), name))
        d += timedelta(days=1)
    with conn() as c:
        c.executemany("INSERT INTO holidays (date, name) VALUES (?,?) "
            "ON CONFLICT (date) DO UPDATE SET name = excluded.name", rows)
    return len(rows)


def day_type(d: date, holidays: dict[str, str] | set[str] | None = None) -> str:
    """weekday or weekend. Holidays are flagged on the calendar but count as the
    normal weekday/weekend shift they fall on (they are not scheduled separately)."""
    return "weekend" if d.weekday() >= 5 else "weekday"


def holiday_label(d: date, holidays: dict[str, str]) -> str:
    """'' if not a holiday, else the holiday's name (or 'Holiday' if unnamed)."""
    iso = d.isoformat()
    if iso not in holidays:
        return ""
    return holidays[iso] or "Holiday"


# ------------------------------------------------------------- availability
def get_person_avail(block_id: int, person_id: int) -> dict[str, str]:
    rows = query(
        "SELECT date, level FROM availability WHERE block_id=? AND person_id=?",
        (block_id, person_id),
    )
    return {r["date"]: r["level"] for r in rows}


def save_person_avail(block_id: int, person_id: int, avail: dict[str, str]) -> None:
    with conn() as c:
        c.execute(
            "DELETE FROM availability WHERE block_id=? AND person_id=?", (block_id, person_id)
        )
        c.executemany(
            "INSERT INTO availability (block_id, person_id, date, level) VALUES (?,?,?,?)",
            [(block_id, person_id, d, lvl) for d, lvl in avail.items() if lvl in LEVELS],
        )


def set_day_avail(block_id: int, person_id: int, iso: str, level: str | None) -> None:
    """Set (or clear, when level is None) one person's availability for one date."""
    with conn() as c:
        c.execute(
            "DELETE FROM availability WHERE block_id=? AND person_id=? AND date=?",
            (block_id, person_id, iso),
        )
        if level in LEVELS:
            c.execute(
                "INSERT INTO availability (block_id, person_id, date, level) VALUES (?,?,?,?)",
                (block_id, person_id, iso, level),
            )


def set_days_avail(block_id: int, person_id: int, isos: list[str], level: str | None) -> None:
    """Bulk version of set_day_avail."""
    with conn() as c:
        c.executemany(
            "DELETE FROM availability WHERE block_id=? AND person_id=? AND date=?",
            [(block_id, person_id, i) for i in isos],
        )
        if level in LEVELS:
            c.executemany(
                "INSERT INTO availability (block_id, person_id, date, level) VALUES (?,?,?,?)",
                [(block_id, person_id, i, level) for i in isos],
            )


def get_block_avail(block_id: int) -> dict[str, dict[int, str]]:
    """date -> {person_id: level}, active people only."""
    out: dict[str, dict[int, str]] = {}
    rows = query(
        """SELECT a.date, a.person_id, a.level FROM availability a
           JOIN people p ON p.id = a.person_id
           WHERE a.block_id=? AND p.active=1""",
        (block_id,),
    )
    for r in rows:
        out.setdefault(r["date"], {})[r["person_id"]] = r["level"]
    return out


# -------------------------------------------------------------- assignments
def get_assignments(block_id: int) -> dict[str, int]:
    rows = query("SELECT date, person_id FROM assignments WHERE block_id=?", (block_id,))
    return {r["date"]: r["person_id"] for r in rows}


def save_assignments(block_id: int, assigned: dict[str, int | None]) -> None:
    with conn() as c:
        c.execute("DELETE FROM assignments WHERE block_id=?", (block_id,))
        c.executemany(
            "INSERT INTO assignments (block_id, date, person_id) VALUES (?,?,?)",
            [(block_id, d, pid) for d, pid in assigned.items() if pid],
        )


def set_assignment(block_id: int, iso: str, person_id: int | None) -> None:
    """Assign one date (or clear it when person_id is None)."""
    with conn() as c:
        c.execute("DELETE FROM assignments WHERE block_id=? AND date=?", (block_id, iso))
        if person_id:
            c.execute(
                "INSERT INTO assignments (block_id, date, person_id) VALUES (?,?,?)",
                (block_id, iso, person_id),
            )


# -------------------------------------------------------------------- stats
def person_stats(block_id: int) -> dict[int, dict]:
    """Per active person: volunteer counts for this block, plus assigned shift
    counts by type for this block and lifetime (carryover + all blocks)."""
    hol = get_holidays()
    stats: dict[int, dict] = {}
    for p in get_people():
        stats[p["id"]] = {
            "name": p["name"],
            "pref": 0,
            "will": 0,
            "vol": 0,
            "life": {"weekday": p["carry_weekday"], "weekend": p["carry_weekend"]},
            "block": {"weekday": 0, "weekend": 0},
            "carry": {"weekday": p["carry_weekday"], "weekend": p["carry_weekend"]},
            "hol_block": 0,  # info only: assigned dates this block that are flagged holidays
        }
    for r in query("SELECT person_id, level FROM availability WHERE block_id=?", (block_id,)):
        s = stats.get(r["person_id"])
        if not s:
            continue
        s["vol"] += 1
        s["pref" if r["level"] == "Preferred" else "will"] += 1
    for r in query("SELECT block_id, date, person_id FROM assignments"):
        s = stats.get(r["person_id"])
        if not s:
            continue
        t = day_type(date.fromisoformat(r["date"]), hol)
        s["life"][t] += 1
        if r["block_id"] == block_id:
            s["block"][t] += 1
            if r["date"] in hol:
                s["hol_block"] += 1
    return stats


# ------------------------------------------------------ ranking / autofill
MODES = {
    "pickup": "Most pick-up first (volunteers for the most dates)",
    "balance": "Balance first (fewest lifetime shifts of that type)",
}


def rank_candidates(
    d: date, avail_d: dict[int, str], stats: dict[int, dict], mode: str, hol: dict[str, str]
) -> list[int]:
    """Order the people who volunteered for date d, best first.
    Preferred always outranks Willing; then the chosen mode; then name."""
    t = day_type(d, hol)

    def key(pid: int):
        lvl = 0 if avail_d[pid] == "Preferred" else 1
        s = stats[pid]
        if mode == "pickup":
            return (lvl, -s["vol"], s["life"][t], s["name"])
        return (lvl, s["life"][t], sum(s["block"].values()), s["name"])

    return sorted((p for p in avail_d if p in stats), key=key)


def autofill(block_id: int, mode: str = "pickup", max_per_person: int = 0) -> int:
    """Fill dates that have no assignment yet. Hardest dates (fewest volunteers)
    first. Never overrides an existing assignment. Returns number filled."""
    block = query("SELECT * FROM blocks WHERE id=?", (block_id,))[0]
    hol = get_holidays()
    avail = get_block_avail(block_id)
    assigned: dict[str, int | None] = dict(get_assignments(block_id))
    stats = person_stats(block_id)

    todo = [d for d in block_dates(block) if d.isoformat() in avail and d.isoformat() not in assigned]
    todo.sort(key=lambda d: (len(avail[d.isoformat()]), d))

    filled = 0
    for d in todo:
        iso = d.isoformat()
        ranked = rank_candidates(d, avail[iso], stats, mode, hol)
        if max_per_person:
            ranked = [p for p in ranked if sum(stats[p]["block"].values()) < max_per_person]
        if not ranked:
            continue
        pick = ranked[0]
        assigned[iso] = pick
        t = day_type(d, hol)
        stats[pick]["block"][t] += 1
        stats[pick]["life"][t] += 1
        filled += 1
    save_assignments(block_id, assigned)
    return filled


# ------------------------------------------------------------------ summary
def summary_df(block_id: int) -> pd.DataFrame:
    stats = person_stats(block_id)
    rows = []
    for s in stats.values():
        b, life = s["block"], s["life"]
        n_assigned = sum(b.values())
        rows.append(
            {
                "Person": s["name"],
                "Preferred": s["pref"],
                "Willing": s["will"],
                "Volunteered": s["vol"],
                "Assigned (block)": n_assigned,
                "Weekday": b["weekday"],
                "Weekend": b["weekend"],
                "Holidays (incl.)": s["hol_block"],
                "Lifetime weekday": life["weekday"],
                "Lifetime weekend": life["weekend"],
                "Lifetime total": sum(life.values()),
            }
        )
    df = pd.DataFrame(rows)
    return df.sort_values(["Volunteered", "Person"], ascending=[False, True]).reset_index(drop=True) if len(df) else df


# -------------------------------------------------------------- excel export
def schedule_df(block_id: int) -> pd.DataFrame:
    block = query("SELECT * FROM blocks WHERE id=?", (block_id,))[0]
    hol = get_holidays()
    assigned = get_assignments(block_id)
    people = {p["id"]: p["name"] for p in get_people(active_only=False)}
    return pd.DataFrame(
        [
            {
                "Date": d.isoformat(),
                "Day": d.strftime("%a"),
                "Type": day_type(d, hol),
                "Holiday": holiday_label(d, hol),
                "Assigned": people.get(assigned.get(d.isoformat()), ""),
            }
            for d in block_dates(block)
        ]
    )


def schedule_xlsx(block_id: int) -> bytes:
    """Formatted workbook: Schedule (every date), By person, Summary."""
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.utils import get_column_letter

    block = query("SELECT * FROM blocks WHERE id=?", (block_id,))[0]
    sched = schedule_df(block_id)
    summ = summary_df(block_id)

    head_font = Font(bold=True, color="FFFFFF")
    head_fill = PatternFill("solid", fgColor="1F4E78")
    fills = {
        "weekend": PatternFill("solid", fgColor="DDEBF7"),
        "holiday": PatternFill("solid", fgColor="FCE4D6"),
    }
    gap_font = Font(color="C00000", italic=True)

    def header(ws, cols, widths):
        ws.append(cols)
        for i, w in enumerate(widths, 1):
            cell = ws.cell(row=ws.max_row, column=i)
            cell.font, cell.fill = head_font, head_fill
            cell.alignment = Alignment(horizontal="center")
            ws.column_dimensions[get_column_letter(i)].width = w
        ws.freeze_panes = f"A{ws.max_row + 1}"

    wb = Workbook()

    # Schedule
    ws = wb.active
    ws.title = "Schedule"
    ws.append([f"{block['name']}  ({block['start_date']} to {block['end_date']})"])
    ws["A1"].font = Font(bold=True, size=14)
    header(ws, ["Date", "Day", "Type", "Holiday", "Assigned"], [13, 7, 11, 22, 26])
    for r in sched.itertuples(index=False):
        ws.append([date.fromisoformat(r.Date), r.Day, r.Type.title(), r.Holiday, r.Assigned or "UNASSIGNED"])
        row = ws.max_row
        ws.cell(row=row, column=1).number_format = "mm/dd/yyyy"
        fill = fills["holiday"] if r.Holiday else fills.get(r.Type)
        if fill:
            for col in range(1, 6):
                ws.cell(row=row, column=col).fill = fill
        if not r.Assigned:
            ws.cell(row=row, column=5).font = gap_font
    ws.auto_filter.ref = f"A2:E{ws.max_row}"

    # By person
    wp = wb.create_sheet("By person")
    header(wp, ["Person", "Date", "Day", "Type", "Holiday"], [26, 13, 7, 11, 22])
    taken = sched[sched["Assigned"] != ""].sort_values(["Assigned", "Date"])
    for r in taken.itertuples(index=False):
        wp.append([r.Assigned, date.fromisoformat(r.Date), r.Day, r.Type.title(), r.Holiday])
        wp.cell(row=wp.max_row, column=2).number_format = "mm/dd/yyyy"
    if wp.max_row > 1:
        wp.auto_filter.ref = f"A1:E{wp.max_row}"

    # Summary
    wsum = wb.create_sheet("Summary")
    cols = list(summ.columns) if len(summ) else ["Person"]
    header(wsum, cols, [26] + [12] * (len(cols) - 1))
    for r in summ.itertuples(index=False):
        wsum.append([_plain(v) for v in r])

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


# -------------------------------------------------------- preferences export
def preferences_xlsx(block_id: int) -> bytes:
    """Everyone's Preferred/Willing picks for a block.
    Sheets: Grid (dates x people, color-coded), By person (long list), Totals."""
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.utils import get_column_letter

    block = query("SELECT * FROM blocks WHERE id=?", (block_id,))[0]
    hol = get_holidays()
    rows = query(
        """SELECT a.date, a.level, p.id AS pid, p.name, p.active FROM availability a
           JOIN people p ON p.id = a.person_id WHERE a.block_id=? ORDER BY p.name, a.date""",
        (block_id,),
    )
    people = sorted({(r["name"], r["pid"]) for r in rows})
    pick = {(r["date"], r["pid"]): r["level"] for r in rows}

    head_font = Font(bold=True, color="FFFFFF")
    head_fill = PatternFill("solid", fgColor="1F4E78")
    fill = {
        "Preferred": PatternFill("solid", fgColor="C6EFCE"),
        "Willing": PatternFill("solid", fgColor="FFEB9C"),
        "weekend": PatternFill("solid", fgColor="DDEBF7"),
        "holiday": PatternFill("solid", fgColor="FCE4D6"),
    }

    def header(ws, cols, widths, row=1):
        for i, (c, w) in enumerate(zip(cols, widths), 1):
            cell = ws.cell(row=row, column=i, value=c)
            cell.font, cell.fill = head_font, head_fill
            cell.alignment = Alignment(horizontal="center", wrap_text=True)
            ws.column_dimensions[get_column_letter(i)].width = w

    wb = Workbook()

    # Grid
    ws = wb.active
    ws.title = "Grid"
    ws.append([f"{block['name']}  ({block['start_date']} to {block['end_date']}) - P = Preferred, W = Willing"])
    ws["A1"].font = Font(bold=True, size=13)
    cols = ["Date", "Day", "Type", "Holiday", "# Preferred", "# Willing"] + [n for n, _ in people]
    header(ws, cols, [12, 6, 10, 18, 11, 10] + [12] * len(people), row=2)
    ws.row_dimensions[2].height = 45
    for d in block_dates(block):
        iso = d.isoformat()
        levels = [pick.get((iso, pid), "") for _, pid in people]
        h = holiday_label(d, hol)
        ws.append([d, d.strftime("%a"), day_type(d).title(), h,
                   levels.count("Preferred"), levels.count("Willing")]
                  + [{"Preferred": "P", "Willing": "W"}.get(x, "") for x in levels])
        r = ws.max_row
        ws.cell(row=r, column=1).number_format = "mm/dd/yyyy"
        base = fill["holiday"] if h else fill["weekend"] if d.weekday() >= 5 else None
        if base:
            for c in range(1, 7):
                ws.cell(row=r, column=c).fill = base
        for i, lvl in enumerate(levels, 7):
            cell = ws.cell(row=r, column=i)
            cell.alignment = Alignment(horizontal="center")
            if lvl:
                cell.fill = fill[lvl]
    ws.freeze_panes = "E3"
    ws.auto_filter.ref = f"A2:{get_column_letter(len(cols))}{ws.max_row}"

    # By person
    wp = wb.create_sheet("By person")
    header(wp, ["Person", "Date", "Day", "Type", "Holiday", "Preference"], [24, 12, 6, 10, 18, 12])
    for r in rows:
        d = date.fromisoformat(r["date"])
        wp.append([r["name"], d, d.strftime("%a"), day_type(d).title(), holiday_label(d, hol), r["level"]])
        wp.cell(row=wp.max_row, column=2).number_format = "mm/dd/yyyy"
        wp.cell(row=wp.max_row, column=6).fill = fill[r["level"]]
    wp.freeze_panes = "A2"
    if wp.max_row > 1:
        wp.auto_filter.ref = f"A1:F{wp.max_row}"

    # Totals
    wt = wb.create_sheet("Totals")
    header(wt, ["Person", "Preferred", "Willing", "Total", "Weekend days", "Holiday days"], [24, 11, 10, 9, 13, 13])
    for name, pid in people:
        mine = [(iso, lvl) for (iso, p), lvl in pick.items() if p == pid]
        n_p = sum(lvl == "Preferred" for _, lvl in mine)
        n_w = sum(lvl == "Willing" for _, lvl in mine)
        n_we = sum(date.fromisoformat(i).weekday() >= 5 for i, _ in mine)
        n_h = sum(i in hol for i, _ in mine)
        wt.append([name, n_p, n_w, n_p + n_w, n_we, n_h])

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
